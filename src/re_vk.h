/**
 * @brief Opens the system Vulkan loader and resolves every entry point.
 *
 * Uses dlopen("libvulkan.so.1") / LoadLibraryA("vulkan-1.dll") plus
 * dlsym/GetProcAddress for the two trampolines, then vkGetInstanceProcAddr
 * for instance-level functions and vkGetDeviceProcAddr for device-level
 * functions (called later, when a device exists).
 *
 * @param api Table to fill.
 * @return True when the loader opened and the trampolines resolved.
 */
bool re_vk_load_api(ReVkApi *api);

/**
 * @brief Resolves the device-level functions of the table. Must be
 *        called once a VkDevice exists and before any device call.
 * @param api Table (instance-level entries already resolved).
 * @param instance VkInstance.
 * @param device VkDevice.
 */
void re_vk_load_device(ReVkApi *api, VkInstance instance, VkDevice device);

