/**
 * @file re_vk.h
 * @brief Raw Vulkan 1.3 dynamic loader: the function table ReVkApi and
 *        re_vk_load_api().
 *
 * Real Engine never links against libvulkan. When RE_HAS_VULKAN is
 * defined (the build detects <vulkan/vulkan.h>), the system loader
 * libvulkan.so.1 is opened with dlopen at runtime, vkGetInstanceProcAddr
 * is resolved with dlsym, and every function below is fetched through
 * the instance/device proc-address entry points — the SDK headers are
 * used only as a compile-time ABI description, per the engine contract
 * "no external loader dependencies".
 *
 * When RE_HAS_VULKAN is not defined, this header is empty and the
 * renderer compiles to the null implementation only.
 */
